class LegacyServer:
    """Expose old test names while applying patches to their owning modules."""

    def __init__(self, adapter: Any) -> None:
        object.__setattr__(self, "_adapter", adapter)
        owners = {}
        for name, symbols in _OWNER_NAMES.items():
            module = importlib.import_module("cite_check_engine." + name)
            owners.update({symbol: module for symbol in symbols})
        object.__setattr__(self, "_owners", owners)

    def __getattr__(self, name: str) -> Any:
        if name in self._owners:
            return getattr(self._owners[name], name)
        if name == "__file__":
            return self._adapter.__file__
        try:
            return getattr(self._adapter, name)
        except AttributeError:
            for module in set(self._owners.values()):
                if hasattr(module, name):
                    return getattr(module, name)
            raise

    def __setattr__(self, name: str, value: Any) -> None:
        if name in self._owners:
            setattr(self._owners[name], name, value)
        else:
            setattr(self._adapter, name, value)

    def __delattr__(self, name: str) -> None:
        if name in self._owners:
            delattr(self._owners[name], name)
        else:
            delattr(self._adapter, name)
